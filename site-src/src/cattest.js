import * as THREE from "three";
import { RoomEnvironment } from "three/examples/jsm/environments/RoomEnvironment.js";
import { createCat } from "./cat.js";
const renderer = new THREE.WebGLRenderer({ antialias: true });
renderer.setSize(1200, 700);
renderer.outputColorSpace = THREE.SRGBColorSpace;
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.shadowMap.enabled = true;
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color("#EDE4FA");
const pm = new THREE.PMREMGenerator(renderer);
scene.environment = pm.fromScene(new RoomEnvironment(), 0.04).texture;
scene.environmentIntensity = 0.3;
scene.add(new THREE.HemisphereLight("#fff", "#D8C6F2", 0.8));
const sun = new THREE.DirectionalLight("#FFF1E6", 2.2);
sun.position.set(3, 6, 5); sun.castShadow = true; scene.add(sun);
const floor = new THREE.Mesh(new THREE.PlaneGeometry(20, 20), new THREE.MeshStandardMaterial({ color: "#F3E6D8" }));
floor.rotation.x = -Math.PI / 2; floor.receiveShadow = true; scene.add(floor);
const a = createCat(); a.group.position.set(-1.3, 0, 0); a.group.rotation.y = 0.3; scene.add(a.group);
const b = createCat(); b.group.position.set(0.2, 0, 0); b.group.rotation.y = -0.2; scene.add(b.group);
const c = createCat({ body: "#DCD0F4", accent: "#A58BD8", inner: "#F2B8D0", whisker: "#8A79B0", bellyColor: "#F4EFFC", sheen: "#FFFFFF" });
c.group.position.set(1.6, 0, 0); c.group.rotation.y = -0.6; scene.add(c.group);
a.pose(1, 1, 0, { x: 0.2, y: 0 }, true, 0);
b.pose(0, 1, 0, { x: 0, y: 0 }, true, 0);
c.pose(1, 1, 0, { x: -0.3, y: 0.1 }, true, 1);
const cam = new THREE.PerspectiveCamera(30, 1200 / 700, 0.1, 50);
cam.position.set(0.2, 1.6, 5.2); cam.lookAt(0.1, 0.55, 0);
renderer.render(scene, cam);
window.__done = true;
